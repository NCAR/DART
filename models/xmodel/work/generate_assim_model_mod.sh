subroutine write_model_time(ncid, model_time, domain_id)
!----------------------------------------------------------------------
integer,         intent(in) :: ncid
type(time_type), intent(in) :: model_time
integer, optional, intent(in) :: domain_id

integer :: model_idx

if (.not. present(domain_id)) then
   ! No domain specified - use first model (single domain case)
   print*, 'HELEN No domain_id provided to write_model_time - using first model by default'
EOF

# Use first model as default
first_model="${MODELS[0]}"
short_name="${MODEL_SHORT_NAMES[$first_model]}"
cat >> "$OUTPUT_FILE" <<EOF
   call ${short_name}_write_model_time(ncid, model_time)
EOF

cat >> "$OUTPUT_FILE" <<'EOF'
else
   ! Look up which model owns this domain
   if (domain_id < 1 .or. domain_id > MAX_DOMAINS) then
      call error_handler(E_ERR, 'write_model_time', 'Invalid domain_id', source)
   endif
   
   model_idx = domain_to_model(domain_id)
   write(*, *) 'DEBUG write_model_time: domain_id =', domain_id, 'maps to model_idx =', model_idx
   
   if (model_idx < 1 .or. model_idx > num_models) then
      write(*, *) 'ERROR: model_idx out of range. num_models =', num_models
      call error_handler(E_ERR, 'write_model_time', 'Domain not registered to any model', source)
   endif
   
   write(*, *) 'DEBUG: Calling write_model_time for model:', trim(model_names(model_idx))
   
   ! Call the appropriate model's write_model_time based on model_idx
EOF

# Generate routing based on model_idx using integer comparison
model_count=0
for model in "${MODELS[@]}"; do
  model_count=$((model_count + 1))
  short_name="${MODEL_SHORT_NAMES[$model]}"
  
  if [ $model_count -eq 1 ]; then
    cat >> "$OUTPUT_FILE" <<EOF
   if (model_idx == ${model_count}) then
      call ${short_name}_write_model_time(ncid, model_time)
EOF
  else
    cat >> "$OUTPUT_FILE" <<EOF
   else if (model_idx == ${model_count}) then
