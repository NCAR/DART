subroutine get_state_meta_data(index_in, location, var_type)
!----------------------------------------------------------------------
! Returns the location and type of a state variable
! Determines which model owns this index and calls appropriate routine
!----------------------------------------------------------------------

integer(i8),         intent(in)  :: index_in
type(location_type), intent(out) :: location
integer, optional,   intent(out) :: var_type

integer :: model_idx, i

! Find which model owns this state index
model_idx = -1
do i = 1, num_models
   if (index_in >= model_offsets(i) .and. &
       index_in < model_offsets(i) + model_sizes(i)) then
      model_idx = i
      exit
   endif
enddo

if (model_idx == -1) then
   call error_handler(E_ERR, 'get_state_meta_data', &
        'Index not found in any model', source)
endif

! Call the appropriate model's get_state_meta_data based on model_idx
EOF

# Generate if-then-else for get_state_meta_data using integer comparison
model_count=0
for model in "${MODELS[@]}"; do
  model_count=$((model_count + 1))
  short_name="${MODEL_SHORT_NAMES[$model]}"
  
  if [ $model_count -eq 1 ]; then
    cat >> "$OUTPUT_FILE" <<EOF
if (model_idx == ${model_count}) then
   call ${short_name}_get_state_meta_data(index_in, location, var_type)
EOF
  else
    cat >> "$OUTPUT_FILE" <<EOF
else if (model_idx == ${model_count}) then
   call ${short_name}_get_state_meta_data(index_in, location, var_type)
EOF
  fi
done

cat >> "$OUTPUT_FILE" <<'EOF'
else
   call error_handler(E_ERR, 'get_state_meta_data', &
        'Invalid model_idx', source)
endif

end subroutine get_state_meta_data

