set -e

if [ $# -lt 1 ]; then
  echo "Usage: $0 <output_file>"
  echo "  output_file: path for generated assim_model_mod.f90"
  exit 1
fi

OUTPUT_FILE=$1

export DART=$(git rev-parse --show-toplevel)
XMODEL_DIR="$DART/models/xmodel/work"

# Load configuration
source "$XMODEL_DIR/model_config.sh"
setup_lags

echo "Generating assim_model_mod.f90 for models: ${MODELS[@]}"

# Standard model_mod interfaces that need to be wrapped
ROUTINES=(
  "get_model_size"
  "static_init_model"
  "get_state_meta_data"
  "shortest_time_between_assimilations"
  "init_conditions"
  "init_time"
  "adv_1step"
  "end_model"
  "pert_model_copies"
  "get_close_obs"
  "get_close_state"
  "convert_vertical_obs"
  "convert_vertical_state"
  "model_interpolate"
  "read_model_time"
  "write_model_time"
  "nc_write_model_atts"
)

#-------------------------
# Generate the file
#-------------------------

cat > "$OUTPUT_FILE" <<'EOF'
! DART software - Copyright UCAR. This open source software is provided
! by UCAR, "as is", without charge, subject to all terms of use at
! http://www.image.ucar.edu/DAReS/DART/DART_download

!> Multi-model version of assim_model_mod
!> This module wraps multiple model_mod modules to support 
!> assimilation with multiple models in a single executable.
!>
!> AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
!> Generated by generate_assim_model_mod.sh
!> Edit model_config.sh to change which models are included
!>
!> DOMAIN MANAGEMENT:
!> Each model can have one or more domains. After calling static_init_model
!> for each model, assim_model_mod tracks which domains belong to which model.
!> This allows write_model_time() to route to the correct model
!> based on the domain parameter.

module assim_model_mod

use    types_mod, only : r8, i8

use time_manager_mod, only : time_type,                                            &
                             operator(<), operator(>), operator(+), operator(-),   &
                             operator(/), operator(*), operator(==), operator(/=)

use ensemble_manager_mod, only : ensemble_type

use utilities_mod, only : error_handler, E_ERR, E_MSG

use location_mod, only : location_type

use state_structure_mod, only : get_num_domains

use obs_kind_mod, only : get_num_quantities, get_index_for_quantity

EOF

# Generate use statements for each model
echo "! Import the renamed model_mod modules" >> "$OUTPUT_FILE"
echo "! These are generated by preprocessing the original model_mod.f90 files" >> "$OUTPUT_FILE"

for model in "${MODELS[@]}"; do
  short_name="${MODEL_SHORT_NAMES[$model]}"
  
  cat >> "$OUTPUT_FILE" <<EOF
use ${short_name}_model_mod, only : &
EOF
  
  # Add renamed imports for each routine
  for i in "${!ROUTINES[@]}"; do
    routine="${ROUTINES[$i]}"
    if [ $i -eq $((${#ROUTINES[@]} - 1)) ]; then
      # Last one, no comma
      echo "    ${short_name}_${routine} => ${routine}" >> "$OUTPUT_FILE"
    else
      echo "    ${short_name}_${routine} => ${routine}, &" >> "$OUTPUT_FILE"
    fi
  done
  
  echo "" >> "$OUTPUT_FILE"
done

# Continue with the rest of the module
cat >> "$OUTPUT_FILE" <<'EOF'
implicit none
private

public :: static_init_assim_model, &
          end_assim_model, &
          get_initial_condition, &
          get_closest_state_time_to, &
          get_state_meta_data, &
          get_model_time_step, &
          get_model_size,  &
          adv_1step, &
          interpolate, &
          pert_model_copies, &
          get_close_obs, &
          get_close_state, &
          convert_vertical_obs, &
          convert_vertical_state, &
          read_model_time, &
          write_model_time, &
          nc_write_model_atts

! Ensure init code is called exactly once
logical :: module_initialized = .false.

! Model size tracking
integer :: num_models
integer, allocatable :: model_sizes(:)
integer, allocatable :: model_offsets(:)  ! Starting index for each model in state vector
integer :: total_model_size

! Model names for identification
character(len=32), allocatable :: model_names(:)

! Domain tracking - maps domain_id to model_idx
integer, parameter :: MAX_DOMAINS = 100
integer :: domain_to_model(MAX_DOMAINS)
integer :: num_domains
integer, allocatable :: model_domain_start(:)  ! First domain_id for each model
integer, allocatable :: model_domain_count(:)  ! Number of domains for each model

! QTY routing - maps observation quantity to model_idx for interpolate
integer, allocatable :: qty_to_model(:)
integer :: default_interp_model  ! Model index for unmapped quantities

! version controlled file description
character(len=*), parameter :: source   = 'xmodel/assim_model_mod.f90'

!-------------------------------------------------------------

contains

!======================================================================

subroutine static_init_assim_model()
!----------------------------------------------------------------------
! Initializes the multi-model assim_model
! Calls static_init_model for each component model
!----------------------------------------------------------------------

integer :: model_idx
! Track domains before and after each model initialization
integer :: domains_before, domains_after, domain_idx

! only execute this code once, even if called multiple times.
if (module_initialized) return

module_initialized = .true.

EOF

# Set number of models directly
cat >> "$OUTPUT_FILE" <<EOF
num_models = ${#MODELS[@]}
EOF

cat >> "$OUTPUT_FILE" <<'EOF'

if (num_models == 0) then
   call error_handler(E_ERR, 'static_init_assim_model', &
        'No models enabled', source)
endif

allocate(model_sizes(num_models))
allocate(model_offsets(num_models))
allocate(model_names(num_models))
allocate(model_domain_start(num_models))
allocate(model_domain_count(num_models))

! Initialize domain tracking
domain_to_model(:) = -1
num_domains = 0
model_domain_count(:) = 0

! Initialize each model and get its size
model_idx = 0
total_model_size = 0

EOF

for model in "${MODELS[@]}"; do
  short_name="${MODEL_SHORT_NAMES[$model]}"
  
  cat >> "$OUTPUT_FILE" <<EOF
model_idx = model_idx + 1
model_names(model_idx) = '${short_name}'

! Track domains before initialization
domains_before = get_num_domains()

call ${short_name}_static_init_model()

! Track domains after initialization
domains_after = get_num_domains()
model_domain_start(model_idx) = domains_before + 1
model_domain_count(model_idx) = domains_after - domains_before

! Automatically register domains to this model
do domain_idx = domains_before + 1, domains_after
   domain_to_model(domain_idx) = model_idx
   num_domains = max(num_domains, domain_idx)
   write(*, *) 'DEBUG: Registered domain', domain_idx, 'to model', model_idx, '(', trim(model_names(model_idx)), ')'
enddo

model_sizes(model_idx) = ${short_name}_get_model_size()
model_offsets(model_idx) = total_model_size + 1
total_model_size = total_model_size + model_sizes(model_idx)
write(*, *) 'Model ', model_idx, ': ', trim(model_names(model_idx)), &
            ' Size: ', model_sizes(model_idx), ' Offset: ', model_offsets(model_idx), &
            ' Domains: ', model_domain_count(model_idx), &
            ' (', model_domain_start(model_idx), '-', domains_after, ')'

EOF
done

cat >> "$OUTPUT_FILE" <<'EOF'
write(*, *) 'Multi-model initialization complete'
write(*, *) 'Number of models: ', num_models
write(*, *) 'Total state size: ', total_model_size
write(*, *) ''
write(*, *) '=== DOMAIN TO MODEL MAPPING ==='
do domain_idx = 1, num_domains
   if (domain_to_model(domain_idx) > 0) then
      write(*, *) 'Domain', domain_idx, '-> Model', domain_to_model(domain_idx), &
                  '(', trim(model_names(domain_to_model(domain_idx))), ')'
   endif
enddo
write(*, *) '==============================='
write(*, *) ''

! Initialize observation quantity routing for interpolate
call init_qty_routing()

end subroutine static_init_assim_model

!======================================================================

subroutine init_qty_routing()
!----------------------------------------------------------------------
! Initialize mapping from observation quantities to models
! Based on configuration from model_config.sh
!----------------------------------------------------------------------
integer :: num_qtys, qty_index, model_idx
integer :: i

num_qtys = get_num_quantities()
allocate(qty_to_model(num_qtys))

! Initialize all to default model
EOF

# Determine default model index - lag models are never used for interpolation
default_model_found=0
default_idx=1
for i in "${!MODELS[@]}"; do
  model="${MODELS[$i]}"
  # Skip lag models - interpolate always routes to the base model
  if [[ "$model" =~ _lag[0-9]+$ ]]; then
    continue
  fi
  short_name="${MODEL_SHORT_NAMES[$model]}"
  idx=$((i + 1))
  if [ "$short_name" == "$DEFAULT_INTERPOLATE_MODEL" ]; then
    default_model_found=1
    default_idx=$idx
    break
  fi
done

if [ $default_model_found -eq 0 ]; then
  echo "WARNING: DEFAULT_INTERPOLATE_MODEL '$DEFAULT_INTERPOLATE_MODEL' not found in MODELS"
  echo "         Using first model as default"
  default_idx=1
fi

cat >> "$OUTPUT_FILE" <<EOF
default_interp_model = ${default_idx}
qty_to_model(:) = default_interp_model

write(*, *) ''
write(*, *) '=== QUANTITY TO MODEL ROUTING ==='
write(*, *) 'Default interpolate model: ', trim(model_names(default_interp_model))
write(*, *) ''

EOF

# Generate qty mapping for each model - lag models are never used for interpolation
for model in "${MODELS[@]}"; do
  # Skip lag models - interpolate always routes to the base model
  if [[ "$model" =~ _lag[0-9]+$ ]]; then
    continue
  fi
  short_name="${MODEL_SHORT_NAMES[$model]}"
  qtys="${MODEL_QTYS[$short_name]}"
  
  if [ -z "$qtys" ]; then
    continue  # Skip models with no explicit QTYs
  fi
  
  # Get model index
  model_idx=0
  for i in "${!MODELS[@]}"; do
    if [ "${MODELS[$i]}" == "$model" ]; then
      model_idx=$((i + 1))
      break
    fi
  done
  
  cat >> "$OUTPUT_FILE" <<EOF
! Assign QTYs to model: ${short_name}
write(*, *) 'Model ${short_name} handles:'
EOF
  
  # Process each QTY for this model
  for qty in $qtys; do
    cat >> "$OUTPUT_FILE" <<EOF
qty_index = get_index_for_quantity('${qty}')
if (qty_index > 0 .and. qty_index <= num_qtys) then
   qty_to_model(qty_index) = ${model_idx}
   write(*, *) '  - ${qty}'
else
   call error_handler(E_MSG, 'init_qty_routing', &
        'Unknown QTY: ${qty}', source)
endif
EOF
  done
  
  cat >> "$OUTPUT_FILE" <<EOF

EOF
done

cat >> "$OUTPUT_FILE" <<'EOF'
write(*, *) '====================================='
write(*, *) ''

end subroutine init_qty_routing

